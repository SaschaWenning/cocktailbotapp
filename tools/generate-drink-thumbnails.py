"""Regenerate overview previews; requires Pillow only on the development machine."""
from pathlib import Path
import json
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1] / "app"
source = root / "assets/drinks"
target = root / "assets/drink_previews"
mapping = {}
original_bytes = preview_bytes = 0
for path in sorted(source.rglob("*")):
    if not path.is_file() or path.suffix.lower() not in {".png", ".jpg", ".jpeg", ".webp"}:
        continue
    relative = path.relative_to(source)
    output = target / relative.parent / (relative.name + ".webp")
    output.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(path) as image:
        image = ImageOps.exif_transpose(image).convert("RGBA")
        image.thumbnail((400, 400), Image.Resampling.LANCZOS)
        image.save(output, "WEBP", quality=80, method=6)
    mapping[path.relative_to(root).as_posix()] = output.relative_to(root).as_posix()
    original_bytes += path.stat().st_size
    preview_bytes += output.stat().st_size
(root / "lib/drink_previews.dart").write_text(
    "// Generated by tools/generate-drink-thumbnails.py.\n"
    "const drinkPreviews = <String, String>{\n" +
    "".join("  " + json.dumps(k, ensure_ascii=False) + ": " + json.dumps(v, ensure_ascii=False) + ",\n" for k, v in mapping.items()) + "};\n",
    encoding="utf-8",
)
print(f"{len(mapping)} previews: {original_bytes:,} -> {preview_bytes:,} bytes")
